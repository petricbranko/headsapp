// Generates src/lib/logos.generated.ts with only the icons the catalog uses (Simple Icons, CC0).
// Run after editing the catalog: node scripts/gen-logos.mjs
import * as si from "simple-icons";
import { writeFileSync } from "node:fs";

const MAP = {
  vercel: "vercel", netlify: "netlify", cloudflare: "cloudflare", gcp: "googlecloud", digitalocean: "digitalocean", hetzner: "hetzner",
  flyio: "flydotio", render: "render", railway: "railway", firebase: "firebase", supabase: "supabase", mongodb: "mongodb", postgresql: "postgresql",
  mysql: "mysql", redis: "redis", neon: "neon", planetscale: "planetscale", upstash: "upstash", prisma: "prisma", auth0: "auth0", okta: "okta",
  clerk: "clerk", stripe: "stripe", paddle: "paddle", lemonsqueezy: "lemonsqueezy", paypal: "paypal", shopify: "shopify", resend: "resend",
  mailgun: "mailgun", mailchimp: "mailchimp", anthropic: "anthropic", openrouter: "openrouter", huggingface: "huggingface", langchain: "langchain",
  github: "github", gitlab: "gitlab", bitbucket: "bitbucket", "npm-registry": "npm", docker: "docker", circleci: "circleci", jenkins: "jenkins",
  jetbrains: "jetbrains", nextjs: "nextdotjs", react: "react", nodejs: "nodedotjs", express: "express", nuxt: "nuxt", sveltekit: "svelte",
  remix: "reactrouter", vite: "vite", laravel: "laravel", django: "django", rails: "rubyonrails", wordpress: "wordpress", php: "php", nginx: "nginx",
  apache: "apache", caddy: "caddy", linux: "linux", ubuntu: "ubuntu", kubernetes: "kubernetes", openssl: "openssl", sentry: "sentry",
  datadog: "datadog", posthog: "posthog", mixpanel: "mixpanel", discord: "discord", notion: "notion", linear: "linear", figma: "figma",
  "google-workspace": "google", "1password": "1password", lastpass: "lastpass", zapier: "zapier",
  // not catalog tools, used by the UI
  whatsapp: "whatsapp", apple: "apple",
};

const out = {};
for (const [slug, key] of Object.entries(MAP)) {
  const icon = si["si" + key.charAt(0).toUpperCase() + key.slice(1)];
  if (!icon) { console.warn("missing", key); continue; }
  out[slug] = { path: icon.path, hex: icon.hex };
}
writeFileSync(
  "src/lib/logos.generated.ts",
  `// Generated by scripts/gen-logos.mjs from Simple Icons (CC0-1.0). Do not edit.\nexport const LOGOS: Record<string, { path: string; hex: string }> = ${JSON.stringify(out)};\n`,
);
console.log(`wrote ${Object.keys(out).length} logos`);
